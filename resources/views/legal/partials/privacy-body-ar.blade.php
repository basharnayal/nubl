<section>
    <h2>1. مقدمة</h2>
    <p>
        تلتزم منصة نُبل بحماية خصوصية المستخدمين وسرية معلوماتهم الشخصية، وتتعامل مع البيانات وفق الضوابط النظامية والتنظيمية المعمول بها في المملكة العربية السعودية، وبما يتوافق مع طبيعة الخدمات التي تقدمها المنصة للمستفيدين والمزوّدين والمتبرعين والإدارة.
    </p>
    <p>
        باستخدامك للمنصة، فإنك تقر باطلاعك على هذه السياسة وموافقتك على ما ورد فيها.
    </p>
</section>

<section>
    <h2>2. البيانات التي قد نجمعها</h2>
    <p>قد تجمع المنصة البيانات التالية بحسب نوع المستخدم والخدمة المستخدمة:</p>

    <h3>أ. البيانات التي يقدمها المستخدم مباشرة</h3>
    <ul>
        <li>الاسم الكامل</li>
        <li>رقم الهوية أو بيانات التحقق ذات العلاقة</li>
        <li>رقم الجوال</li>
        <li>البريد الإلكتروني</li>
        <li>المدينة أو معلومات الموقع العام</li>
        <li>بيانات الحساب وتفضيلات الاستخدام</li>
        <li>بيانات الطلبات أو التبرعات أو الخدمات المطلوبة</li>
        <li>المستندات أو المرفقات أو الإثباتات المقدمة</li>
        <li>الرسائل أو الملاحظات أو الطلبات المرسلة عبر المنصة</li>
    </ul>

    <h3>ب. البيانات الناتجة عن استخدام المنصة</h3>
    <ul>
        <li>عنوان IP</li>
        <li>نوع المتصفح ونظام التشغيل والجهاز</li>
        <li>وقت وتاريخ الدخول</li>
        <li>الصفحات أو الشاشات التي تم الوصول إليها</li>
        <li>سجلات التفاعل مع الخدمة</li>
        <li>المعرفات التقنية وملفات تعريف الارتباط عند الاستخدام</li>
    </ul>

    <h3>ج. البيانات التشغيلية المرتبطة بالخدمة</h3>
    <ul>
        <li>حالة الطلبات ودورة حياتها داخل المنصة</li>
        <li>سجلات التحقق أو الاستلام أو الإتمام</li>
        <li>سجلات الدفع أو التبرع عند توفرها</li>
        <li>سجلات التدقيق والأمان والأنشطة النظامية</li>
    </ul>
</section>

<section>
    <h2>3. الغرض من جمع البيانات</h2>
    <p>تُجمع البيانات وتُستخدم للأغراض التالية:</p>
    <ul>
        <li>إنشاء الحسابات وإدارة الوصول والصلاحيات</li>
        <li>تقديم الخدمات الرقمية وتشغيل المنصة</li>
        <li>استقبال الطلبات ومراجعتها واعتمادها ومتابعتها</li>
        <li>إدارة التبرعات أو المساهمات أو المعاملات ذات العلاقة</li>
        <li>التحقق من الهوية والأهلية وصحة الإجراءات</li>
        <li>تمكين التحقق من الاستلام أو التنفيذ أو الإتمام</li>
        <li>التواصل مع المستخدمين وإشعارهم بحالة الطلبات أو العمليات</li>
        <li>تحسين الأداء وتجربة الاستخدام وتطوير الخدمات</li>
        <li>حماية المنصة من الاحتيال أو إساءة الاستخدام أو الوصول غير المصرح به</li>
        <li>الامتثال للمتطلبات النظامية والتنظيمية</li>
        <li>إعداد تقارير أو مؤشرات تشغيلية أو إحصائية بشكل لا يخل بسرية البيانات الشخصية</li>
    </ul>
</section>

<section>
    <h2>4. الأساس النظامي لمعالجة البيانات</h2>
    <p>قد تستند معالجة البيانات إلى واحد أو أكثر من الأسس التالية:</p>
    <ul>
        <li>موافقة صاحب البيانات عند الاقتضاء</li>
        <li>تنفيذ التزام تعاقدي أو تقديم خدمة طلبها المستخدم</li>
        <li>الامتثال لالتزام نظامي أو تنظيمي</li>
        <li>تحقيق مصلحة مشروعة للمنصة بما لا يتعارض مع حقوق صاحب البيانات</li>
        <li>حماية المنصة أو المستخدمين من الاحتيال أو إساءة الاستخدام أو المخاطر الأمنية</li>
    </ul>
</section>

<section>
    <h2>5. مشاركة البيانات والإفصاح عنها</h2>
    <p>
        لا يتم بيع البيانات الشخصية للمستخدمين. ومع ذلك، قد يتم الإفصاح عن البيانات أو مشاركتها في الحدود اللازمة مع:
    </p>
    <ul>
        <li>الجهات المخولة نظامًا</li>
        <li>الجهات أو الشركاء الفنيين أو التشغيليين المرتبطين بتقديم الخدمة</li>
        <li>مزودي خدمات الدفع أو التحقق أو الاستضافة أو الإشعارات أو الدعم الفني</li>
        <li>الجهات ذات العلاقة بتنفيذ الطلب أو التبرع أو الإجراء داخل المنصة</li>
        <li>الجهات التي يتطلب النظام أو القرار المختص تزويدها بالبيانات</li>
    </ul>
    <p>
        ويتم ذلك وفق حدود الحاجة وبما يتناسب مع الغرض المشروع، مع اتخاذ التدابير المناسبة لحماية السرية.
    </p>
</section>

<section>
    <h2>6. تخزين البيانات والاحتفاظ بها</h2>
    <p>
        تحتفظ المنصة بالبيانات الشخصية والسجلات التشغيلية للمدة اللازمة لتحقيق الأغراض المذكورة في هذه السياسة، أو للمدة التي تتطلبها الأنظمة أو الإجراءات التنظيمية أو متطلبات الحماية والتدقيق أو تسوية النزاعات، ثم تُتلف أو تُخفى هويتها وفق ما تسمح به الأنظمة والإجراءات المعتمدة.
    </p>
</section>

<section>
    <h2>7. حماية البيانات وأمن المعلومات</h2>
    <p>
        تتخذ المنصة تدابير تقنية وتنظيمية مناسبة لحماية البيانات من الفقد أو الوصول غير المصرح به أو التعديل أو الإفصاح أو الإتلاف، بما في ذلك ما يلزم من وسائل الحماية مثل:
    </p>
    <ul>
        <li>التحكم في الصلاحيات والوصول</li>
        <li>التشفير أو الحماية التقنية المناسبة عند الحاجة</li>
        <li>مراقبة الأنشطة والسجلات</li>
        <li>النسخ الاحتياطي واستمرارية الأعمال</li>
        <li>الضوابط الأمنية الخاصة بالأنظمة والخوادم</li>
    </ul>
    <p>
        ومع ذلك، لا يمكن ضمان الحماية بنسبة 100% في أي بيئة إلكترونية، ويقر المستخدم بذلك مع التزام المنصة ببذل العناية المعقولة.
    </p>
</section>

<section>
    <h2>8. ملفات تعريف الارتباط والتقنيات المشابهة</h2>
    <p>
        قد تستخدم المنصة ملفات تعريف الارتباط أو التقنيات المشابهة لتحسين الأداء وتخصيص التجربة وفهم أنماط الاستخدام وتسهيل تسجيل الدخول أو حفظ التفضيلات. ويمكن للمستخدم تعديل إعدادات المتصفح للتحكم في هذه الملفات، مع العلم أن بعض خصائص المنصة قد تتأثر نتيجة لذلك.
    </p>
</section>

<section>
    <h2>9. نقل البيانات ومعالجتها</h2>
    <p>
        قد تتم معالجة البيانات أو استضافتها أو النسخ الاحتياطي لها من خلال مزودين أو بنى تحتية تقنية داخل المملكة أو خارجها، وذلك بحسب الحاجة التشغيلية ووفق ما تسمح به الأنظمة والضوابط المعمول بها، مع اتخاذ الإجراءات اللازمة لضمان مستوى مناسب من الحماية.
    </p>
</section>

<section>
    <h2>10. حقوق صاحب البيانات</h2>
    <p>وفقًا للأنظمة ذات العلاقة، قد يكون لصاحب البيانات عدد من الحقوق، ومنها:</p>
    <ul>
        <li>الحق في العلم بطريقة جمع البيانات وأساسها والغرض منها</li>
        <li>الحق في الوصول إلى بياناته الشخصية</li>
        <li>الحق في طلب تصحيح البيانات غير الدقيقة أو غير المكتملة</li>
        <li>الحق في طلب إتلاف البيانات عند انتفاء الحاجة النظامية أو المشروعة للاحتفاظ بها</li>
        <li>الحق في سحب الموافقة في الحالات التي تكون المعالجة قائمة عليها، وذلك دون الإخلال بمشروعية المعالجة السابقة</li>
        <li>أي حقوق أخرى تقررها الأنظمة واللوائح ذات العلاقة</li>
    </ul>
    <p>
        ويتم التعامل مع الطلبات المتعلقة بهذه الحقوق وفق الإجراءات والقنوات المعتمدة في المنصة وبما لا يتعارض مع المتطلبات النظامية أو الأمنية أو الحقوق المشروعة للغير.
    </p>
</section>

<section>
    <h2>11. خصوصية السجلات التشغيلية وسرية المعلومات</h2>
    <p>
        قد تحتفظ المنصة بسجلات تشغيلية وأمنية وتدقيقية تتعلق باستخدام الخدمات، بما في ذلك السجلات المرتبطة بالطلبات أو التبرعات أو التحقق أو التنفيذ أو الدخول أو التعديل أو الإتمام، وذلك لأغراض الحماية، والامتثال، والتوثيق، والتحسين، ومنع إساءة الاستخدام.
    </p>
    <p>
        وتعامل هذه السجلات باعتبارها معلومات سرية، ولا يتم الاطلاع عليها أو الإفصاح عنها إلا في حدود الحاجة التشغيلية أو النظامية أو الأمنية.
    </p>
</section>

<section>
    <h2>12. التعديلات على السياسة</h2>
    <p>
        تحتفظ المنصة بحق تعديل أو تحديث هذه السياسة في أي وقت، وتصبح النسخة المعدلة نافذة من تاريخ نشرها على المنصة ما لم يُذكر خلاف ذلك. ويُعد استمرار المستخدم في استخدام المنصة بعد نشر التحديث موافقة على السياسة بصيغتها المحدثة.
    </p>
</section>

