<section>
    <h2>1. ما هي منصة نُبل؟</h2>
    <p>
        نُبل منصة رقمية خيرية تهدف إلى تسهيل ربط المستفيدين بالجهات المزوّدة والداعمين، وتمكين إدارة الطلبات والمساهمات المالية والعينية ومتابعة تنفيذها إلكترونيًا وفق الضوابط التشغيلية المعتمدة. وتوفّر المنصة خدمات تشمل تقديم الطلبات، مراجعتها، اعتمادها، تبنّيها، متابعتها، وتنفيذها وتوثيق إتمامها.
    </p>
</section>

<section>
    <h2>2. قبول الشروط</h2>
    <p>
        يُعد استخدامك لمنصة نُبل، أو إنشاء حساب فيها، أو الاستفادة من أي من خدماتها، موافقة صريحة منك على هذه الشروط والأحكام وعلى جميع السياسات ذات العلاقة، بما في ذلك سياسة الخصوصية. وإذا كنت لا توافق على هذه الشروط، فيجب عليك التوقف عن استخدام المنصة.
    </p>
</section>

<section>
    <h2>3. أهلية الاستخدام</h2>
    <p>
        يلتزم المستخدم بأن تكون جميع البيانات المقدمة صحيحة ودقيقة ومحدّثة. ويجوز للمنصة تقييد أو تعليق أو إنهاء الوصول إلى الخدمات في حال تقديم معلومات غير صحيحة أو مضللة، أو عند إساءة استخدام المنصة أو مخالفة الأنظمة أو هذه الشروط.
    </p>
</section>

<section>
    <h2>4. حسابات المستخدمين</h2>
    <p>قد تتيح المنصة إنشاء حسابات لفئات مختلفة من المستخدمين، بما في ذلك:</p>
    <ul>
        <li>المستفيد</li>
        <li>المزوّد / الجهة المنفذة</li>
        <li>المتبرع / الداعم</li>
        <li>الإدارة</li>
    </ul>
    <p>
        ويتحمل كل مستخدم مسؤولية المحافظة على سرية بيانات الدخول الخاصة به، وكافة الأنشطة التي تتم من خلال حسابه، ويلتزم بإبلاغ إدارة المنصة فورًا عند الاشتباه بأي استخدام غير مصرح به.
    </p>
</section>

<section>
    <h2>5. طبيعة خدمات المنصة</h2>
    <p>
        تعمل نُبل كمنصة رقمية لإدارة وتنسيق الطلبات والمساهمات والخدمات المرتبطة بها، بما يشمل استقبال الطلبات، التحقق منها، عرضها على الجهات ذات العلاقة، متابعة حالة الطلب، وتوثيق تنفيذه عند الاقتضاء. ولا يعني ظهور الطلب في المنصة أو استقباله أو مراجعته وجود التزام نهائي بقبوله أو تنفيذه أو تمويله إلا بعد استكمال الإجراءات والضوابط المعتمدة داخل المنصة.
    </p>
</section>

<section>
    <h2>6. الطلبات والموافقات والتنفيذ</h2>
    <p>
        تخضع الطلبات المقدمة عبر المنصة للمراجعة والتحقق والقبول أو الرفض أو الإحالة أو الانتظار وفقًا للضوابط التشغيلية والمالية المعتمدة. ويجوز للمنصة أو للجهة المخولة طلب مستندات أو معلومات إضافية قبل اتخاذ القرار بشأن الطلب.
    </p>
    <p>
        كما قد تختلف حالة الطلب خلال دورة حياته داخل المنصة بحسب نتائج المراجعة أو الاعتماد أو التبنّي أو التنفيذ أو الإلغاء، وتُعد الحالة الظاهرة في حساب المستخدم هي المرجع الرسمي لمتابعة الطلب.
    </p>
</section>

<section>
    <h2>7. التبرعات والمساهمات</h2>
    <p>
        إذا أتاحت المنصة استقبال تبرعات أو مساهمات مالية أو عينية، فإنها تُستخدم وفق الإجراءات والضوابط المعتمدة داخل المنصة. ويقر المستخدم بأن تنفيذ عمليات الدفع أو التحويل أو التحقق منها قد يتم عبر مزودي خدمات دفع أو تكاملات تقنية مع أطراف ثالثة، وتخضع هذه العمليات كذلك لسياسات تلك الجهات بقدر ما ينطبق.
    </p>
    <p>
        ولا تتحمل المنصة المسؤولية عن أي تأخير أو فشل ناتج عن أنظمة الدفع أو الأنظمة التقنية التابعة لجهات خارجية، مع التزامها ببذل الجهد المعقول لمعالجة الإشكالات المرتبطة بالخدمة.
    </p>
</section>

<section>
    <h2>8. التحقق والاستلام والإثبات</h2>
    <p>
        قد تعتمد المنصة آليات تحقق أو استلام إلكترونية، بما في ذلك رموز التحقق أو أكواد الاستلام أو أي وسائل تقنية أخرى، بهدف تأكيد استحقاق الخدمة أو صحة التنفيذ أو إتمام التسليم. ويُعد استخدام هذه الوسائل جزءًا من الإجراءات التشغيلية والأمنية للمنصة، ويُحظر التحايل عليها أو مشاركتها أو استخدامها بطريقة غير مشروعة.
    </p>
    <p>
        كما يجوز للمنصة طلب أو حفظ إثباتات مرتبطة بإتمام التنفيذ أو التسليم متى كان ذلك لازمًا للتحقق أو التوثيق أو الامتثال أو المعالجة التشغيلية.
    </p>
</section>

<section>
    <h2>9. التزامات المستخدم</h2>
    <p>يلتزم المستخدم بالامتناع عن:</p>
    <ul>
        <li>تقديم بيانات أو مستندات غير صحيحة أو مضللة.</li>
        <li>استخدام المنصة لأغراض غير مشروعة أو مخالفة للأنظمة.</li>
        <li>إساءة استخدام الخدمات أو محاولة تعطيل المنصة أو التحايل على آلياتها.</li>
        <li>الوصول غير المصرح به إلى الحسابات أو البيانات أو الواجهات التقنية.</li>
        <li>رفع ملفات ضارة أو محتوى خبيث أو تعليمات برمجية مؤذية.</li>
        <li>استخدام المنصة بما يخل بحقوق المستفيدين أو الجهات المزوّدة أو المتبرعين أو الإدارة.</li>
        <li>إعادة نشر أو نسخ أو استغلال محتوى المنصة أو بياناتها دون إذن.</li>
    </ul>
</section>

<section>
    <h2>10. تعليق الحساب أو إيقاف الخدمة</h2>
    <p>
        يحق للمنصة، وفق ما تراه مناسبًا، تعليق الحساب أو تقييد بعض الصلاحيات أو إيقاف الوصول مؤقتًا أو نهائيًا، وذلك في حال مخالفة هذه الشروط أو وجود اشتباه في إساءة الاستخدام أو لأسباب تشغيلية أو أمنية أو نظامية، دون الإخلال بحقوق المنصة في اتخاذ ما تراه لازمًا.
    </p>
</section>

<section>
    <h2>11. الملكية الفكرية</h2>
    <p>
        جميع الحقوق المتعلقة بالمنصة، بما في ذلك الاسم التجاري، المحتوى، النصوص، التصاميم، الواجهات، قواعد البيانات، البرمجيات، والمخرجات التشغيلية، مملوكة لنُبل أو للجهات المرخصة لها، ومحمية بموجب الأنظمة ذات العلاقة. ولا يجوز نسخ أي جزء منها أو تعديله أو إعادة استخدامه أو نشره دون موافقة خطية مسبقة.
    </p>
</section>

<section>
    <h2>12. التوافر الفني والصيانة</h2>
    <p>
        تبذل المنصة جهدًا معقولًا لتوفير الخدمة واستمراريتها، إلا أنها لا تضمن عدم الانقطاع أو الخلو من الأخطاء أو التأخير، ويجوز تعليق الخدمة كليًا أو جزئيًا لأغراض الصيانة أو التحديث أو التطوير أو لأسباب خارجة عن الإرادة.
    </p>
</section>

<section>
    <h2>13. حدود المسؤولية</h2>
    <p>
        تُقدم خدمات المنصة ومحتوياتها على أساس "كما هي" و"حسب التوفر". ولا تتحمل المنصة المسؤولية عن أي أضرار مباشرة أو غير مباشرة أو تبعية أو خسائر أو فوات منافع تنشأ عن استخدام المنصة أو عدم القدرة على استخدامها أو الاعتماد على أي محتوى أو تأخير أو انقطاع أو عطل تقني أو تصرف صادر من طرف ثالث، وذلك في حدود ما تسمح به الأنظمة المعمول بها.
    </p>
</section>

<section>
    <h2>14. التعويض</h2>
    <p>
        يوافق المستخدم على تعويض المنصة وإدارتها وموظفيها وممثليها عن أي مطالبات أو خسائر أو أضرار أو تكاليف أو التزامات تنشأ عن مخالفته لهذه الشروط أو إساءة استخدامه للمنصة أو انتهاكه للأنظمة أو لحقوق الغير.
    </p>
</section>

<section>
    <h2>15. الروابط والخدمات الخارجية</h2>
    <p>
        قد تحتوي المنصة على روابط أو تكاملات مع مواقع أو أنظمة أو مزودي خدمات من أطراف ثالثة. وتُعرض هذه الخدمات لتيسير الاستخدام، ولا تتحمل المنصة مسؤولية محتواها أو سياساتها أو توافرها أو ما ينتج عن استخدامها.
    </p>
</section>

<section>
    <h2>16. الخصوصية وحماية البيانات</h2>
    <p>
        يخضع جمع البيانات الشخصية ومعالجتها واستخدامها ومشاركتها لسياسة الخصوصية وسرية المعلومات الخاصة بالمنصة، والتي تُعد جزءًا لا يتجزأ من هذه الشروط والأحكام.
    </p>
</section>

<section>
    <h2>17. التعديلات على الشروط</h2>
    <p>
        تحتفظ المنصة بحق تعديل أو تحديث هذه الشروط والأحكام في أي وقت، وتصبح التعديلات نافذة من تاريخ نشرها على المنصة ما لم يُذكر خلاف ذلك. ويُعد استمرار المستخدم في استخدام المنصة بعد التحديث موافقة على الشروط المعدلة.
    </p>
</section>

<section>
    <h2>18. النظام الحاكم والاختصاص</h2>
    <p>
        تخضع هذه الشروط والأحكام للأنظمة المعمول بها في المملكة العربية السعودية، وتختص الجهات القضائية أو الجهات المختصة داخل المملكة بالنظر في أي نزاع ينشأ بشأنها، ما لم يقتض النظام خلاف ذلك.
    </p>
</section>

<section>
    <h2>19. التواصل</h2>
    <p>
        للاستفسارات أو الملاحظات المتعلقة بهذه الشروط والأحكام، يمكن التواصل عبر القنوات الرسمية المعتمدة في المنصة.
    </p>
</section>
